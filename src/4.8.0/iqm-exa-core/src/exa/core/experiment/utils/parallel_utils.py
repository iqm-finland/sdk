def get_color_grouped_sweeps(
    components: ComponentGrouping,
    chip_topology: ChipTopology,
    settings: SettingNode,
    group_sweep_generation_function: SweepGenerationFunction,
    **kwargs,
) -> Sweeps:
    """Generate sweeps using a group-wise sweep generation function.

    The group-wise sweep generation function acts on a single parallelly runnable group of the experiment. The sweeps
    are generated by combining the contributions of each parallel group within each parallelly runnable partition of
    the QPU (color).

    Args:
        components: Color grouped components (names).
        chip_topology: The chip topology.
        settings: The settings tree.
        group_sweep_generation_function: The function should have the args ``group`` (of type ``tuple[str, ...]``),
            containing the names of the components in the parallel group, and ``chip_topology``
            (of type :class:`.ChipTopology`).
        kwargs: Additional arguments for ``group_sweep_generation_function``.

    Returns:
        The generated sweeps.

    """
    all_groups = [group for color in components for group in color]
    sweeps: NdSweep = []
    for _i, group in enumerate(all_groups):
        group_ndsweep = convert_sweeps_to_list_of_tuples(
            group_sweep_generation_function(group, chip_topology, settings, **kwargs)
        )
        # merge sweeps with the same index into ParallelSweeps
        for j, group_parallelsweep in enumerate(group_ndsweep):
            if len(sweeps) < j + 1:
                # first part of this ParallelSweep
                sweeps.append(group_parallelsweep)
            elif group_parallelsweep[0].parameter != sweeps[j][0].parameter:
                # extend the ParallelSweep
                sweeps[j] += group_parallelsweep
    return sweeps  # type: ignore[return-value]  # list invariance, harmless here but annoying


def group_is_subscribed(
    group: list[str] | tuple[str], properties: dict, chip_topology: ChipTopology, settings: SettingNode
) -> bool:
    """Utility for testing if a component group has been subscribed.

    Only components which have readouts are considered as it is impossible to subscribe a component which does not have
    readout.

    Args:
        group: Component group.
        properties: Additional readout properties.
        chip_topology: The chip topology.
        settings: The settings tree.

    Returns:
        A boolean denoting if the group has been subscribed.

    """
    if "time_trace_data_parameters" in properties and any(
        component in tr_parameter
        for component in group
        for tr_parameter in properties["time_trace_data_parameters"] + properties["integration_data_parameters"]
        if component in chip_topology.probe_lines
    ):
        return True
    set_group = {
        component
        for component in group
        if component in settings.controllers.children
        and component in settings.gates.measure[settings.get_default_implementation_name("measure", component)].children
    }
    return any(set(readout_group).intersection(set_group) for readout_group in properties["readout_groups"])


def get_coupler_from_mapping(qubits: tuple[str, str], mapping: dict[str, list[str]]) -> str | None:
    """Get coupler from a given mapping.

    Args:
        qubits: qubit names.
        mapping: coupler mapping.

    Returns:
        The coupler name or `None` if the coupler is not found.

    """
    for key in mapping:  # noqa: PLC0206
        if mapping[key] == [qubits[0], qubits[1]] or mapping[key] == [qubits[1], qubits[0]]:
            return key
    return None


def color_grouped_analysis(
    run_result: RunResult,
    group_analyze_function: AnalyzeFunction,
    chip_topology: ChipTopology,
    chip_layout: ChipLayout,
    chip_properties: ChipProperties,
    gate_definitions: QuantumOpTable,
    components: ComponentGrouping | None,
    **kwargs,
) -> AnalyzeResult:
    """Perform the full color grouped analysis by applying the group-wise function to each group and color group.

    Args:
        run_result: The run result containing the full dataset and run data.
        group_analyze_function: The group-wise analyze function.
        chip_topology: Chip topology.
        chip_layout: Chip layout.
        chip_properties: Properties extracted from station control's chip design record.
        gate_definitions: Mapping of names of gates and operations to their definitions.
        components: Limit the analysis to these components.
        kwargs: passed to `group_analyze_function`.

    Returns:
        The full analyze result.

    """
    dataset = run_result.dataset
    properties = run_result.run_definition.additional_run_properties
    force_ragged_data = run_result.run_definition.options["force_ragged_data"]
    component_groups = properties["components"]  # type: ignore[index]
    analyze_components = ComponentGrouping(components)
    analyze_sig = set(signature(group_analyze_function).parameters.keys())

    analyze_result = AnalyzeResult(run_result=run_result)
    settings = analyze_result.run_result.run_definition.sweep_definition.settings

    groups_not_subscribed = []
    for circuit_index, color in enumerate(component_groups):
        for group in color:
            if not analyze_components or analyze_components.contains(group):
                if group_is_subscribed(group, properties, chip_topology, settings):  # type: ignore[arg-type]
                    data_color = get_data_color(dataset, circuit_index, len(component_groups), force_ragged_data)
                    auto_args = {
                        "group": group,
                        "chip_topology": chip_topology,
                        "chip_layout": chip_layout,
                        "chip_properties": chip_properties,
                        "gate_definitions": gate_definitions,
                        "run_result": run_result,
                        "data_color": data_color,
                        "settings": settings,
                        "circuit_index": circuit_index,
                        "analyze_result": analyze_result,
                    }
                    for not_wanted in set(auto_args.keys()) - analyze_sig:
                        del auto_args[not_wanted]

                    partial_result = group_analyze_function(**auto_args, **kwargs)
                    if partial_result is not None:
                        analyze_result.observations.extend(partial_result.observations)
                        analyze_result.plots.update(partial_result.plots)
                else:
                    groups_not_subscribed.append(group)

    if len(groups_not_subscribed) > 0:
        warning_template = (
            "The analysis was not performed on the following groups: %GROUPS% due to them "
            "not being subscribed (i.e. read out) in the experiment."
        )
        logger.warning(warning_template.replace("%GROUPS%", str(groups_not_subscribed)))

    return analyze_result


def plot_with_circuit_index(plotting_function: Callable[..., Figure], circuit_index: int, *args, **kwargs) -> Figure:
    """Handles the `circuit_index==1` case for plotting.

    If `circuit_index==1`, the `circuit_index` dimension is not present in the data, and the whole dataset
    should be used for the plotting.

    Args:
        plotting_function: The plotting function.
        circuit_index: The circuit index.
        args: Args given to plotting function.
        kwargs: Kwargs given to plotting function.

    Returns:
        Wrapped plot with the `circuit_index` dimension handled correctly.

    """
    args_list = list(args)
    run_result: RunResult = args_list[0]
    if any(CIRCUIT_SWEEP_PARAMETER.name in dim for dim in run_result.dataset.dims):  # type: ignore[operator]
        # replace the RunResult
        force_ragged = run_result.run_definition.options["force_ragged_data"]
        run_result = RunResult(
            run_definition=run_result.run_definition,
            dataset=get_data_color(run_result.dataset, circuit_index, 0, force_ragged),
            timeline=run_result.timeline,
        )
        args_list[0] = run_result
        args = tuple(args_list)
    return plotting_function(*args, **kwargs)


@deprecated(
    format_deprecated(old="wrap_2qb_plot_for_circuit_dimension", new="plot_with_circuit_index", since="2026-10-28")
)
def wrap_2qb_plot_for_circuit_dimension(plotting_function: Callable, circuit_index: int) -> Callable:
    """Handles the `circuit_index==1` case for plotting.

    If `circuit_index==1`, the `circuit_index` dimension is not present in the data, and the whole dataset
    should be used for the plotting.

    Args:
        plotting_function: The plotting function.
        circuit_index: The circuit index.

    Returns:
        Wrapped plot with the `circuit_index` dimension handled correctly.

    """
    return partial(plot_with_circuit_index, plotting_function, circuit_index)


def process_singular_run_components(
    components: ComponentGrouping, chip_topology: ChipTopology, options: ExperimentOptions
) -> tuple[ComponentGrouping, list[str] | dict[str, list[str]]]:
    """Process components into "groups" of just a single component.

    Singular components can be always color grouped into a single color, but the user may provide several colors
    if they want.

    Args:
        components: The components.
        chip_topology: The chip topology.
        options: The experiment options.

    Returns:
        Components grouped into single-component groups

    """
    if not components:
        components = ComponentGrouping(list(chip_topology.qubits_sorted))
    if components.grouping_mode == ComponentGroupingMode.LIST:
        components = ComponentGrouping([[(c,) for c in components]])  # type: ignore[arg-type]
    elif components.grouping_mode == ComponentGroupingMode.GROUP:
        components = ComponentGrouping([components.to_list()])  # type: ignore[arg-type]
    if options.subscribed_components is not None:
        return components, options.subscribed_components
    if options.readout_mode == ReadoutMode.COUNTER.value:
        return components, {q: [q] for q in components.flatten()}
    return components, components.flatten()


def process_probe_lines(
    components: ComponentGrouping, chip_topology: ChipTopology, options: ExperimentOptions
) -> tuple[ComponentGrouping, list[str] | dict[str, list[str]]]:
    """Process probe lines (a special case of :func:`.process_singular_run_components`).

    If no components are given, returns all probe lines found in the chip. The subscribed components are the same probe
    lines as well.

    Args:
        components: The components.
        chip_topology: The chip topology.
        options: The experiment options.

    Returns:
        Probe lines grouped into single-component groups.

    """
    if not components:
        components = ComponentGrouping(list(chip_topology.probe_lines_sorted))
    grouped, subscribed_components = process_singular_run_components(components, chip_topology, options)
    return grouped, subscribed_components


def process_components_to_pairs(
    components: ComponentGrouping,
    chip_topology: ChipTopology,
    options: ExperimentOptions,
    allow_both: bool = True,
) -> tuple[ComponentGrouping, list[str] | dict[str, list[str]]]:
    """Processes the run arg `components` into a list of parallelly runnable lists of pairs of a qubit and a computational
    resonator or two qubits.

    If no components are provided, all connected pairs will be colored into parallelly runnable partitions.

    If the counter readout is used, the returned `subscribed_components` are the pairwise readout groups.
    Otherwise, a flat list of all the active qubits are returned.

    Args:
        components: the components which can be a list, list of tuples or a list of lists of tuples (already
            colored). If an already colored partitioning is provided, it assumed to be correctly colored.
        chip_topology: The chip topology.
        options: The experiment options.
        allow_both: If True, allows both qubit-qubit and qubit-resonator pairs. If False, allows only qubit-resonator
            pairs.

    Returns:
        Run components (colored list of parallelly runnable sets of pairs) and the subscribed components.

    Raises:
        ValueError: if the inputted components do not have any qubit-computational resonator or qubit-qubit pairs
        connected via a coupler.

    """  # noqa: E501

    def coupler_mapping_from_topology(some_qubits: list[str], some_resonators: list[str]) -> dict[str, list[str]]:
        """Given some qubits and some computational resonators, returns a dictionary containing only those couplers as
        keys, which only connect to components in either of these lists, either a qubit and a computational resonator
        or two qubits.
        """

        # TODO: this functionality needs to be added in ChipTopology
        def enforce_qubit_resonator_order(values: tuple[str, str]):  # noqa: ANN202
            if values[0] in some_qubits and values[1] in some_resonators + allow_both * some_qubits:
                return list(values)
            if values[1] in some_qubits and values[0] in some_resonators:
                return list(values)[::-1]
            return None

        coupler_dict = {
            c: enforce_qubit_resonator_order(v)  # type: ignore[arg-type]
            for c, v in chip_topology.coupler_to_components.items()
            if enforce_qubit_resonator_order(v)  # type: ignore[arg-type]
        }
        return coupler_dict

    if not components or components.grouping_mode == ComponentGroupingMode.LIST:
        qubits_and_resonators = components.to_list()
        component_groups = None
    else:
        qubits_and_resonators = None
        component_groups = components.to_list()
    if not qubits_and_resonators:
        qubits = list(chip_topology.qubits_sorted)
        resonators = list(chip_topology.computational_resonators_sorted)
    else:
        qubits = list(set(chip_topology.qubits_sorted) & set(qubits_and_resonators))
        resonators = list(set(chip_topology.computational_resonators_sorted) & set(qubits_and_resonators))
    all_pairs = list(coupler_mapping_from_topology(qubits, resonators).values())
    coloured_components = ComponentGrouping(
        get_2qb_gate_groups(all_pairs=all_pairs, component_groups=component_groups), False
    )
    if len(coloured_components) == 0:
        raise ValueError(
            "The inputted run components do not seem to have any connections. Cannot run this experiment "
            "without at least one qubit-resonator or qubit-qubit pair connected via a coupler."
        )
    subscribed_components = options.subscribed_components
    if not subscribed_components:
        all_qubits = set(chip_topology.qubits_sorted)
        all_resonators = set(chip_topology.computational_resonators_sorted)

        subscribed_components = (
            coupler_mapping_from_topology(
                list(set(coloured_components.flatten()) & all_qubits),
                list(set(coloured_components.flatten()) & all_resonators),
            )
            if options.readout_mode == ReadoutMode.COUNTER.value
            else coloured_components.flatten()
        )
    return coloured_components, subscribed_components


def process_groups_to_colors(
    components: ComponentGrouping,
    chip_topology: ChipTopology,
    options: ExperimentOptions,
) -> tuple[ComponentGrouping, list[str] | dict[str, list[str]]]:
    """Process generic groups into colors if not yet colored.

    Not yet colored groups are colored by allocating the minimum number of colors such that any component is encountered
    only once in each color. Flat lists of components cannot be grouped or colored as there is no information
    on how this should be done.

    Args:
        components: the components which can be a list, list of tuples or a list of lists of tuples (already
            colored). If an already colored partitioning is provided, it assumed to be correctly colored.
        chip_topology: The chip topology.
        options: The experiment options.

    Raises:
        ValueError: if flat list of components is provided.

    """
    if components.grouping_mode == ComponentGroupingMode.LIST or not components:
        raise ValueError(
            "Only grouped components are supported with parallel_group=COLORED_GROUPS"
            f", whereas your components={components}."
        )
    if components.grouping_mode == ComponentGroupingMode.GROUP:
        # create coloring by allocating the minimum number of colors such that no component appears twice
        # in a single color
        coloured_components: list[list[tuple[str, ...]]] = [[]]
        for group in components:
            color_found = False
            group_set = set(group)
            for color in coloured_components:
                components_in_color = set(ComponentGrouping(color, validate=False).flatten())
                if not group_set.intersection(components_in_color):
                    color.append(group)
                    color_found = True
                    break
            if not color_found:
                coloured_components.append([group])
    else:
        coloured_components = components

    subscribed_components = options.subscribed_components
    if not subscribed_components:
        subscribed_components = (
            {"__".join(group): list(group) for color in coloured_components for group in color}
            if options.readout_mode == ReadoutMode.COUNTER.value
            else ComponentGrouping(coloured_components).flatten()
        )
    return ComponentGrouping(coloured_components), subscribed_components


def get_run_components_for_one_colour_group(
    components: ComponentGrouping,
    chip_topology: ChipTopology,
    options,  # noqa: ANN001
    colour_group_index=0,  # noqa: ANN001
) -> tuple[ComponentGrouping, list[str] | dict[str, list[str]]]:
    """Gets run components and subscribed components for just one of the colour groups.

    This helper function can be used to process run components for experiments that cannot
    support running for all colour groups in a single run. For example, if some of the default
    sweeps for the pairs are soft sweeps, it is not possible to express the sweeps over all the
    colour groups due to EXA-limitation where hard and soft sweeps cannot be combined in a tuple
    of sweeps.

    Args:
        components: All the components for the experiment.
        chip_topology: The chip topology.
        options: Experiment options.
        colour_group_index: Index of the chosen colour group.

    Returns:
        Updated colour grouping and a list of updated subscribed components.

    """
    if not components or components.grouping_mode == ComponentGroupingMode.LIST:
        qubits = components.to_list()
        component_groups = None
    else:
        qubits = None
        component_groups = components.to_list()
    if not qubits:
        qubits = chip_topology.qubits_sorted  # type: ignore[assignment]
    all_pairs = [
        list(chip_topology.coupler_to_components[coupler])
        for coupler in chip_topology.get_connecting_couplers(qubits)  # type: ignore[arg-type]
    ]
    coloured_components = ComponentGrouping(
        get_2qb_gate_groups(all_pairs=all_pairs, component_groups=component_groups), False
    )
    if len(coloured_components) == 0:
        raise ValueError(
            "The inputted run components do not seem to have any connections. Cannot run a parallel "
            "two-qubit experiment without at least one qubit-pair connected via a coupler"
        )

    nbr_colour_groups = len(coloured_components)
    if nbr_colour_groups > 1:
        coloured_components = ComponentGrouping([coloured_components[colour_group_index]])
        logger.warning(
            (
                "Only one colour group is supported by the experiment. Got %d groups.",
                " Choosing group %d with pairs %s.",
            ),
            nbr_colour_groups,
            colour_group_index,
            str(coloured_components),
        )

    subscribed_components = options.subscribed_components
    if not subscribed_components:
        subscribed_components = (
            chip_topology.limit_values(chip_topology.coupler_to_components, coloured_components.flatten())  # type: ignore[type-var]
            if options.readout_mode == ReadoutMode.COUNTER.value
            else coloured_components.flatten()
        )
    return coloured_components, subscribed_components


@no_type_check
def get_2qb_gate_groups(
    all_pairs: list[list[str]] | None = None,
    component_groups: list[tuple[str, str]] | list[list[tuple[str, str]], None] = None,
) -> list[tuple[str, str]] | list[list[tuple[str, str]]]:
    """Returns groups of qubit pairs for which 2QB gates can be performed simultaneously."""
    if all_pairs is None:
        all_pairs = []
    if component_groups is None:
        component_groups = [tuple(qubits) for qubits in all_pairs]

    if all(isinstance(component_subgroup, list) for component_subgroup in component_groups):
        # assume the list is already structured and just check if all pairs exist on the chip
        for qubit_pair_list in component_groups:
            for qubit_pair in qubit_pair_list:
                if list(qubit_pair) not in all_pairs and list(qubit_pair)[::-1] not in all_pairs:
                    raise NotFoundError(f"Connection between {qubit_pair[0]} and {qubit_pair[1]} not found")
        return component_groups

    if all(isinstance(component_subgroup, tuple) for component_subgroup in component_groups):
        # assume the list not yet structured
        for qubit_pair in component_groups:
            if list(qubit_pair) not in all_pairs and list(qubit_pair)[::-1] not in all_pairs:
                raise NotFoundError(f"Connection between {qubit_pair[0]} and {qubit_pair[1]} not found")

        # check if qubits repeat, if not, skip coloring
        qubits_in_pairs = [qubit for pair in component_groups for qubit in pair]
        if len(qubits_in_pairs) == len(set(qubits_in_pairs)):
            return [component_groups]
        return color_qubit_pairs(component_groups)
    raise ValueError("Malformed input `component_groups`.")


def get_data_color(dataset: Dataset, circuit_index: int, n_colors: int, force_ragged_data: bool = False) -> Dataset:
    """Select data collected for a particular circuit.

    If different qubits participate in different circuits with a different number of readouts, unrags the ragged arrays.

    Args:
        dataset: Full dataset.
        circuit_index: Index of the circuit.
        n_colors: Number of sequential colors.
        force_ragged_data: TODO

    Returns:
        Unragged, selected dataset.

    """
    # check ragged circuit index
    coords_with_ci = [str(coord) for coord in dataset.coords if "::" + CIRCUIT_SWEEP_PARAMETER.name in str(coord)]
    if not coords_with_ci:
        if n_colors == 1 or CIRCUIT_SWEEP_PARAMETER.name not in dataset.dims:
            return dataset
        else:
            return dataset.isel({CIRCUIT_SWEEP_PARAMETER.name: circuit_index}, drop=True)

    # there are ragged coords so deal with those

    ds_color = dataset.copy()

    for coord in coords_with_ci:
        if coord not in ds_color.coords:
            continue
        label = str(coord).split("::")[0]
        if circuit_index not in ds_color[coord]:
            label_vars = [
                str(lb_var) for lb_var in ds_color if (f"{label}_" in str(lb_var) or f"{label}:" in str(lb_var))
            ] + [
                str(lb_var) for lb_var in ds_color.coords if (f"{label}_" in str(lb_var) or f"{label}:" in str(lb_var))
            ]
            ds_color = ds_color.drop_vars(label_vars)
            continue

        ds_color = ds_color.sel({coord: circuit_index}, drop=True)

    ds_color = ds_color.squeeze(drop=True)
    if CIRCUIT_SWEEP_PARAMETER.name in ds_color.dims:
        ds_color = ds_color.sel({CIRCUIT_SWEEP_PARAMETER.name: circuit_index}, drop=True)

    remaining_ragged = [
        str(coord).replace("_" + RAGGED_DATA_INDEX.name, "")
        for coord in ds_color.coords
        if "_" + RAGGED_DATA_INDEX.name in str(coord)
    ]

    if not force_ragged_data:
        coords_with_trigger = [str(coord) for coord in ds_color.coords if "::" + TRIGGER_INDEX.name in str(coord)]

    else:
        coords_with_trigger = []

    # do not rename for still ragged variables if any
    for label in remaining_ragged:
        if f"{label}::{TRIGGER_INDEX.name}" in coords_with_trigger:
            coords_with_trigger.remove(f"{label}::{TRIGGER_INDEX.name}")

    coords_replaced = [
        str(coord).replace("::" + TRIGGER_INDEX.name, "_" + READOUT_SLOT_SWEEP_PARAMETER.name)
        for coord in coords_with_trigger
    ]

    ds_color = ds_color.rename(dict(zip(coords_with_trigger, coords_replaced)))

    for coord in coords_replaced:
        n_readouts = len(ds_color[coord])
        ds_color[coord] = np.arange(n_readouts)

    return ds_color
